let LANG = "fa";
let LANG_SAVED = false;   // true once this browser has an explicit choice
try {
  const saved = localStorage.getItem("mtp_lang");
  if (saved === "fa" || saved === "en") { LANG = saved; LANG_SAVED = true; }
} catch {}

/* t("key", {n: 3}) -> localized string with {placeholders} filled in */
function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]) ?? I18N.fa[key] ?? key;
  if (vars) for (const k in vars) s = s.split("{" + k + "}").join(vars[k]);
  return s;
}
const num = (n) => Number(n || 0).toLocaleString(LANG === "fa" ? "fa-IR" : "en-US");
const fmtDate = (ts) => new Intl.DateTimeFormat(LANG === "fa" ? "fa-IR-u-ca-persian" : "en-GB",
  { dateStyle: "medium", timeStyle: "short" }).format(new Date(ts * 1000));

/* Apply the language to static markup: data-i18n (text), data-i18n-html, data-i18n-ph (placeholder), data-i18n-title */
function applyStaticI18n(root = document) {
  document.documentElement.lang = LANG;
  document.documentElement.dir = LANG === "fa" ? "rtl" : "ltr";
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-ph]").forEach((el) => { el.placeholder = t(el.dataset.i18nPh); });
  root.querySelectorAll("[data-i18n-title]").forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  root.querySelectorAll(".lang-toggle").forEach((el) => { el.textContent = t("lang_other"); });
}
